// Minimal 5x7 dot-matrix font: only the characters this project's display
// strings actually use (space, A-Z, 0-9, and a handful of punctuation).
// Each glyph is 5 columns; column c's byte packs the glyph's 7 rows into
// bits 0..6 (bit0 = top row), which lines up directly with SSD1306 page
// memory -- no bit-shuffling needed to write a glyph column straight into
// GDDRAM. Unsupported characters (see glyphFor() in ssd1306.cpp) render as
// a blank column rather than garbage, so a typo here is a missing
// character, never a corrupted display.
